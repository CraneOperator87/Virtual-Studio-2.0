let riktigTall = 43;
let gjettet;
gjettet = 17;

console.log(gjettet == riktigTall); // gir false

// == lik verdi
// === lik verdi og datatype
// != ikke lik verdi
// !== ikke lik verdi eller datatype
// > større enn
// < mindre enn
// >= større eller lik
// <= mindre eller lik

console.log(5 == "5"); // true
console.log(5 === "5"); // false

console.log(5 != 4);    // skriver ut true
console.log(5 != 5);    // skriver ut false
console.log(5 != "5");  // skriver ut false
console.log(5 !== 4);   // skriver ut true
console.log(5 !== "5"); // skriver ut true